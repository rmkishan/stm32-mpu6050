/**
  * @brief  Function implementing the ControlTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartControlTask */
void StartControlTask(void *argument)
{
  /* USER CODE BEGIN 5 */
	IMU_State imu;
    float integral = 0.0f;
	uint32_t last_time = HAL_GetTick();


  /* Infinite loop */
    for(;;)
    {
        if (osMessageQueueGet(
                IMUQueueHandle,
                &imu,
                NULL,
                osWaitForever) == osOK)
        {
        	if (system_state != SYSTEM_RUNNING){
        	Motor_SetCommand(0.0f);
        	continue;
        	}

        	uint32_t current_time = HAL_GetTick();
			float dt = (current_time - last_time)/1000.f;
			last_time = current_time;

			float error = TARGET_PITCH - imu.pitch;
			integral += error * dt;

			if (integral > INTEGRAL_LIMIT) {
				integral = INTEGRAL_LIMIT;
			}
			if (integral < -INTEGRAL_LIMIT) {
				integral = -INTEGRAL_LIMIT;
			}

			float derivative = -imu.gyro_y_dps;

        	float motor_command = KP*error + KI*integral + KD * derivative ;

            if (Motor_SetCommand(motor_command) != HAL_OK){
            	printf("Motor command failed\r\n");
            }
            else{
printf(
    "PITCH=%.2f ERR=%.2f I=%.2f GY=%.2f CMD=%.2f\r\n",
    imu.pitch,
    error,
    integral,
    imu.gyro_y_dps,
    motor_command
);
            }

    }
    }
  /* USER CODE END 5 */
}

/* USER CODE BEGIN Header_StartSensorTask */
/**
* @brief Function implementing the SensorTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartSensorTask */
void StartSensorTask(void *argument)
{
  /* USER CODE BEGIN StartSensorTask */
  IMU_State imu;

  uint32_t previous_sample_time = HAL_GetTick();
  HAL_TIM_Base_Start_IT(&htim2);
  /* Infinite loop */
  for(;;)
  {
    osThreadFlagsWait(
        0x01,
        osFlagsWaitAny,
        osWaitForever
    );

    uint32_t current_sample_time = HAL_GetTick();

    float dt =
        (current_sample_time - previous_sample_time)
        / 1000.0f;

    previous_sample_time = current_sample_time;

    if (IMU_Update(dt, &imu) == IMU_OK)
    {
    	osStatus_t queue_status;
        queue_status = osMessageQueuePut(
            IMUQueueHandle,
            &imu,
            0,
            0
        );
        if (queue_status != osOK){
        	printf("WARNING : IMU queue full\r\n");
        }
    }
    else {
        printf("IMU update failed\r\n");

        system_error = ERROR_IMU;
        system_state = SYSTEM_ERROR;
        Motor_SetCommand(0.0f);
    }
  }
  /* USER CODE END StartSensorTask */
}

/* USER CODE BEGIN Header_StartWatchdogTask */
/**
* @brief Function implementing the WatchdogTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartWatchdogTask */
void StartWatchdogTask(void *argument)
{
  /* USER CODE BEGIN StartWatchdogTask */
	uint32_t last_sensor_heartbeat = 0;
	uint32_t last_control_heartbeat = 0;
  /* Infinite loop */
  for(;;)
  {

    osDelay(100);

    if ((sensor_heartbeat != last_sensor_heartbeat) && (control_heartbeat != last_control_heartbeat)) {
    	last_sensor_heartbeat = sensor_heartbeat;
    	last_control_heartbeat = control_heartbeat ;

    	HAL_IWDG_Refresh(&hiwdg);
    }
  }
  /* USER CODE END StartWatchdogTask */
}

